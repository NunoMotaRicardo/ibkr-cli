package cli

import (
	"fmt"
	"strings"

	"github.com/spf13/cobra"

	"github.com/NunoMotaRicardo/ibkr-cli/internal/mcp"
)

const defaultSnapshotPath = "specs/provider/tools-snapshot.json"

func (a *App) toolsCmd() *cobra.Command {
	var search, snapshot, against string
	var refresh, diff, full bool
	c := &cobra.Command{
		Use:   "tools",
		Short: "List the connector's tools (name, kind, one-line summary)",
		Long: "Lists every tool the IBKR connector currently exposes. The list is cached for 24h; --refresh re-fetches.\n" +
			"--diff compares the live list and schemas with the committed snapshot (maintainers).\n" +
			"--snapshot <path> writes a new snapshot from the live list.",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx := cmd.Context()
			live := refresh || diff || snapshot != ""
			tc, err := a.toolCache(ctx, live)
			if err != nil {
				return err
			}
			if snapshot != "" {
				s := mcp.NewSnapshot(a.serverURL(), tc.Tools, a.now())
				s.Note = "Generated by `ibkr tools --snapshot`. Input schemas are signatures (descriptions stripped). Compare with `ibkr tools --diff`."
				if err := mcp.WriteSnapshot(snapshot, s); err != nil {
					return err
				}
				fmt.Fprintf(a.Out, "wrote %s (%d tools)\n", snapshot, len(tc.Tools))
				return nil
			}
			if diff {
				if against == "" {
					against = defaultSnapshotPath
				}
				s, err := mcp.ReadSnapshot(against)
				if err != nil {
					return failErr("cannot read snapshot %s: %v", against, err)
				}
				d := mcp.DiffSnapshot(s, tc.Tools)
				if d.Empty() {
					fmt.Fprintf(a.Out, "no differences: %d live tools match %s\n", len(tc.Tools), against)
					return nil
				}
				for _, n := range d.Added {
					fmt.Fprintf(a.Out, "+ %s\n", n)
				}
				for _, n := range d.Removed {
					fmt.Fprintf(a.Out, "- %s\n", n)
				}
				for _, n := range d.Changed {
					fmt.Fprintf(a.Out, "~ %s\n", n)
				}
				return nil
			}
			var rows []map[string]any
			for _, t := range tc.Tools {
				if search != "" {
					h := strings.ToLower(t.Name + " " + t.Description)
					if !strings.Contains(h, strings.ToLower(search)) {
						continue
					}
				}
				sum := mcp.FirstSentence(t.Description)
				if full {
					sum = strings.TrimSpace(t.Description)
				}
				rows = append(rows, map[string]any{"name": t.Name, "kind": mcp.Classify(t).String(), "summary": sum})
			}
			if a.opts.limit > 0 && len(rows) > a.opts.limit {
				rows = rows[:a.opts.limit]
			}
			res := &Result{List: true, Cols: []string{"name", "kind", "summary"}, Rows: rows}
			if f := parseFields(a.opts.fields); len(f) > 0 {
				res.Cols = f
			}
			return a.writeResult(res)
		},
	}
	c.Flags().StringVar(&search, "search", "", "filter by text in name/description")
	c.Flags().BoolVar(&refresh, "refresh", false, "re-fetch the tool list from the server")
	c.Flags().BoolVar(&diff, "diff", false, "compare the live tools with the committed snapshot")
	c.Flags().StringVar(&against, "against", "", "snapshot file for --diff (default "+defaultSnapshotPath+")")
	c.Flags().StringVar(&snapshot, "snapshot", "", "write a snapshot of the live tools to this path")
	c.Flags().BoolVar(&full, "full", false, "show full descriptions")
	return c
}

func (a *App) describeCmd() *cobra.Command {
	var full bool
	c := &cobra.Command{
		Use:   "describe <tool>",
		Short: "Show a tool's parameters compactly (name, type, required, enum)",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			t, err := a.lookupTool(cmd.Context(), args[0])
			if err != nil {
				return err
			}
			ps := mcp.Params(t.InputSchema)
			if a.opts.raw {
				return a.emitData(map[string]any{"name": t.Name, "description": t.Description, "inputSchema": t.InputSchema}, View{}, nil)
			}
			if a.opts.json {
				var rows []map[string]any
				for _, p := range ps {
					rows = append(rows, map[string]any{"name": p.Name, "type": p.Type, "required": p.Required, "enum": p.Enum, "description": p.Description})
				}
				return a.writeResult(&Result{List: true, Cols: []string{"name", "type", "required", "enum", "description"}, Rows: rows, Meta: [][2]any{{"tool", t.Name}, {"kind", mcp.Classify(t).String()}}})
			}
			desc := mcp.FirstSentence(t.Description)
			if full {
				desc = strings.TrimSpace(t.Description)
			}
			fmt.Fprintf(a.Out, "%s [%s]\n%s\n", t.Name, mcp.Classify(t), desc)
			if len(ps) == 0 {
				fmt.Fprintln(a.Out, "params: none")
				return nil
			}
			fmt.Fprintln(a.Out, "params:")
			for _, p := range ps {
				req := "optional"
				if p.Required {
					req = "required"
				}
				line := fmt.Sprintf("  %s  %s  %s", p.Name, p.Type, req)
				if len(p.Enum) > 0 {
					line += "  enum: " + strings.Join(p.Enum, "|")
				}
				if p.Description != "" {
					line += "  - " + p.Description
				}
				fmt.Fprintln(a.Out, line)
			}
			return nil
		},
	}
	c.Flags().BoolVar(&full, "full", false, "show the full description")
	return c
}

func (a *App) callCmd() *cobra.Command {
	var argsJSON string
	c := &cobra.Command{
		Use:   "call <tool> [key=value ...]",
		Short: "Call any connector tool; values are typed from the tool's schema",
		Long: "Calls any tool by name, including tools added after this CLI was released.\n" +
			"key=value pairs are coerced using the tool's cached JSON schema (integer, number, boolean, array via a,b,c or JSON).\n" +
			"Use --args-json '{...}' for complex arguments. Write tools need --yes. Run `ibkr describe <tool>` first.",
		Args: cobra.MinimumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			t, err := a.lookupTool(cmd.Context(), args[0])
			if err != nil {
				return err
			}
			targs, err := mcp.BuildArgs(t.InputSchema, args[1:], argsJSON)
			if err != nil {
				return usageErr("%v\nRun `ibkr describe %s` to see its parameters.", err, t.Name)
			}
			res, err := a.callTool(cmd.Context(), t, targs, callOpts{})
			if err != nil {
				return err
			}
			if err := a.emit(res, View{}); err != nil {
				return err
			}
			a.printLinks(res, "Link")
			return nil
		},
	}
	c.Flags().StringVar(&argsJSON, "args-json", "", "arguments as a JSON object (key=value pairs override)")
	return c
}
